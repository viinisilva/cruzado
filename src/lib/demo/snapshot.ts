// The public demonstration's head start (docs/DEPLOY_DEMO.md): starting an empty PGlite runs Postgres's initdb, which
// took 6 to 8 s on Vercel. The build saves a database that is already created and migrated, with no rows and no dates,
// and each instance loads it instead. The invented data is still written at start, with that day's dates.
import { readFile } from "node:fs/promises";
import path from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import type { DB } from "@/db/connection";
import { runMigrations } from "@/db/migrate";
import * as schema from "@/db/schema";

// Generated by scripts/demo-build.ts before `next build`, traced into the functions by next.config.ts.
export const DEMO_SNAPSHOT_FILE = path.join(/* turbopackIgnore: true */ process.cwd(), "demo-snapshot", "base.tgz");

/** Creates an empty database with every migration applied and returns its dump. */
export async function buildDemoSnapshot(): Promise<Blob> {
  const client = new PGlite();
  try {
    await runMigrations(drizzle(client, { schema }) as unknown as DB);
    return await client.dumpDataDir("gzip");
  } finally {
    await client.close();
  }
}

/** The dump saved by the build, or undefined (local runs, or a build without it): the caller then runs initdb. */
export async function readDemoSnapshot(file = DEMO_SNAPSHOT_FILE): Promise<Blob | undefined> {
  try {
    return new Blob([await readFile(file)]);
  } catch {
    return undefined;
  }
}
